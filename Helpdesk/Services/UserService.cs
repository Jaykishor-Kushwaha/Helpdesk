        private async Task<int?> ResolveDepartmentIdAsync(int? requestedDepartmentId, int? existingDepartmentId)
        {
            if (requestedDepartmentId.HasValue)
            {
                var isValid = await _context.Departments
                    .AnyAsync(d => d.Id == requestedDepartmentId.Value && d.IsActive);
                if (!isValid)
                    throw new ValidationException("Department is not active or does not exist.");

                return requestedDepartmentId.Value;
            }

            if (existingDepartmentId.HasValue)
                return existingDepartmentId.Value;

            var general = await _context.Departments
                .FirstOrDefaultAsync(d => d.Name == "General" && d.IsActive);
            return general?.Id;
        }

        private int GetActorUserId(int fallbackUserId)
        {
            try
            {
                return _currentUser.UserId;
            }
            catch
            {
                return fallbackUserId;
            }
        }

        /// <summary>
        /// Generates a cryptographically random temporary password that satisfies
        /// the configured Identity password policy.
        /// FIX: replaced System.Random (predictable, clock-seeded) with
        /// RandomNumberGenerator (cryptographically secure).
        /// </summary>
        private string GenerateRandomPassword()
        {
            var options = _userManager.Options.Password;
            int length = options.RequiredLength < 8 ? 8 : options.RequiredLength;

            const string lower = "abcdefghijklmnopqrstuvwxyz";
            const string upper = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
            const string digit = "0123456789";
            const string special = "@$!%*?&";
            const string all = lower + upper + digit + special;

            var chars = new char[length];

            // Guarantee at least one of each required character class
            chars[0] = lower[RandomNumberGenerator.GetInt32(lower.Length)];
            chars[1] = upper[RandomNumberGenerator.GetInt32(upper.Length)];
            chars[2] = digit[RandomNumberGenerator.GetInt32(digit.Length)];
            chars[3] = special[RandomNumberGenerator.GetInt32(special.Length)];

            for (int i = 4; i < length; i++)
                chars[i] = all[RandomNumberGenerator.GetInt32(all.Length)];

            // Shuffle using Fisher-Yates with a secure random index
            for (int i = length - 1; i > 0; i--)
            {
                int j = RandomNumberGenerator.GetInt32(i + 1);
                (chars[i], chars[j]) = (chars[j], chars[i]);
            }

            return new string(chars);
        }
